// Fuzz the .ninja_deps reader (DepsLog::Load).
//
// Threat model: a .ninja_deps file sitting in a foreign source tree (or
// shipped alongside a build.ninja) is parsed by ninja before any build
// command runs, so its bytes are attacker-controlled in that setting. The
// format gates every byte behind checks plain mutation cannot cross: the
// "# ninjadeps\n" magic (deps_log.cc:38), the version word 4
// (deps_log.cc:41), per-record 4-byte size words with a high-bit record-type
// flag, 4-byte alignment padding, and a ~id checksum per path record
// (deps_log.cc:277). Structurally valid seeds are therefore generated by
// misc/oss-fuzz/generate_deps_seeds.py; the fuzzer then mutates within and
// across records.
//
// The harness mirrors manifest_fuzzer.cc's convention of writing the input to
// a temp file: DepsLog::Load only accepts a path, not a buffer.

#include <stdint.h>
#include <stdio.h>
#include <string>

#include "deps_log.h"
#include "state.h"

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  const char* path = "/tmp/fuzz.ninja_deps";
  FILE* fp = fopen(path, "wb");
  if (!fp)
    return 0;
  fwrite(data, 1, size, fp);
  fclose(fp);

  std::string err;
  State state;
  DepsLog deps_log;
  deps_log.Load(path, &state, &err);

  remove(path);
  return 0;
}
